def validate_full_name(full_name: str, gender: str) -> tuple[bool, str]:
    words = full_name.strip().split()

    if len(words) != 3:
        return False, "Нужно ровно 3 слова: Фамилия Имя Отчество"

    surname, name, patronymic = words

    for w in words:
        if not re.match(r"^[А-ЯЁ][а-яё\-]+$", w):
            return (
                False,
                "Каждое слово должно начинаться с большой буквы и содержать только русские буквы",
            )

    # Проверка отчества по полу
    if gender == "male":
        if not patronymic.endswith(("ович", "евич", "ич")):
            return (
                False,
                "Отчество мужчины должно заканчиваться на -ович, -евич или -ич.",
            )
    elif gender == "female":
        if not patronymic.endswith(("овна", "евна", "ична", "инична")):
            return (
                False,
                "Отчество женщины должно заканчиваться на -овна, -евна или -ична.",
            )

    # Проверка имени по полу
    name_lower = name.lower()
    if gender == "male" and name_lower in FEMALE_NAMES:
        return False, f"Имя «{name}» женское, а выбран мужской пол. Введи мужское имя."
    if gender == "female" and name_lower in MALE_NAMES:
        return False, f"Имя «{name}» мужское, а выбран женский пол. Введи женское имя."

    # Если имени нет в списке, просто предупреждаем, но принимаем
    if name_lower not in MALE_NAMES and name_lower not in FEMALE_NAMES:
        return (
            True,
            f"⚠️ Имя «{name}» не найдено в списке. Убедись, что порядок верный: Фамилия Имя Отчество.",
        )

    return True, ""
